# Operadores compuestos

print(f'*** Operadores de asignación compuestos ***')

# Valores iniciales
a, b = 10, 15
print(f'Valores iniciales a = {a}, b = {b}')

# Operador compuesto Suma (+=)
a += b
print(f'Operador a+=b es: {a}')

# Operador compuesto Resta (-=)
a = 10 # reiniciar valor
a -= b
print(f'Operador a-=b es: {a}')

# Operador compuesto multiplicación (*=)
a = 10 # reiniciar valor
a *= b
print(f'Operador a*=b es: {a}')

# Operador compuesto división (/=)
a = 10 # reiniciar valor
a /= b
print(f'Operador a/=b es: {a:.2f}')


