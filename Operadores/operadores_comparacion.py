print(f'*** Operadores de comparación ***')

#Valores iniciales
a, b = 7,5
print(f'Valores iniciales: a = {a}, b = {b}')

# Es igual (==)
resultado = a == b
print(f'Resultado a==b es: {resultado}')

# Es diferente (!=)
resultado = a != b
print(f'Resultado a!=b es: {resultado}')

# Es mayor que (>)
resultado = a > b
print(f'Resultado a>b es: {resultado}')

# Es menor que (<)
resultado = a < b
print(f'Resultado a<b es: {resultado}')

# Es mayor o igual que (>=)
resultado = a >= b
print(f'Resultado a>=b es: {resultado}')

# Es menor o igual que (<=)
resultado = a <= b
print(f'Resultado a <= b es: {resultado}')
