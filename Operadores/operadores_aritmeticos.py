# Operadores Aritméticos
from time import process_time_ns

#Valores
a = 10
b = 3

#Suma (+)
suma = a + b
print(f'El valor  de la suma es: {suma}')

#Resta (-)
resta = a - b
print(f'El valor de la resta es: {resta}')

#Multiplicación (*)
multiplicacion = a * b
print(f'El valor de la multiplicación es: {multiplicacion}')

#División (/)
division = a / b
print(f'El valor de la división es: {division:.2f}')

#División entera (//)
division_entera = a // b
print(f'El valor de la división entera es: {division_entera}')

# Módulo (%) Residuo de la división
modulo = a % b
print(f'El residuo de la división es: {modulo}')

# Potencia (**)
potencia = a ** b
print(f'El valor de la potencia es: {potencia}')

