# Programa para entrada de datos

# 1. Entrada de texto
nombre = input(f'Escribe tu nombre: ')
print(f'Tu nombre es: {nombre}')

# 2. Entrada de numeros y conversiones
edad = input(f'Escribe tu edad: ')
print(f'Tu edad es: {edad}')
print(f'Tu próximo cumpleaños tendrás: {int(edad) + 1}')

# 3. Entrada de decimales
altura = float(input(f'Ingresa tu estatura en metros: '))
print(f'Tu altura es de: {altura}m')