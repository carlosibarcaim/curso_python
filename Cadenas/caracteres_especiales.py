# Salto de lunea \n
mensaje1 = "Hola\nMundo"
print(mensaje1)

# Tabulación \t
# Imprimimos una guía numéricoa para ve las posiciones
print('123412341234123412341234')
mensaje2 = "\t\tCarlos \tIbar"
print(mensaje2)

# Comillas dentro de cadena
mensaje3 = "Ella dijo \"Hola a todos\""
print(mensaje3)

# Barra invertida \
mensaje4 = "C:\\Usuarios\\Ibar\\Documentos"
print(mensaje4)

# Cadenas cruda (raw string) r
mensaje5 = r"C:\Usuarios\Ibar\Documentos"
print(mensaje5)